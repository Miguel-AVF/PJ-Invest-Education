<div>

    <h3>Ações — riscos e diversificação</h3>

    <p>
        O risco de mercado é central nas ações: os preços podem variar diariamente. Uma empresa 
        também pode enfrentar problemas específicos, mudanças regulatórias, concorrência, queda de 
        demanda ou outros eventos. <br>
        Diversificação é uma forma de reduzir a dependência de um único ativo ou setor, mas não elimina 
        o risco. Um conjunto de ações pode continuar sofrendo perdas em uma crise ampla do mercado.
    </p>

</div>

