<div class="informa_intro">

    <h1>Mercado de ações</h1>

    <p>
        Uma ação representa uma parcela do capital de uma empresa. Ao comprar uma ação, o investidor 
        passa a ter uma participação societária conforme as regras daquele ativo. O preço pode variar 
        bastante, e o resultado depende do comportamento do mercado e dos resultados da empresa. <br>
        Ações não funcionam como CDB ou Tesouro Direto: não existe uma taxa fixa de rendimento 
        prometida para o investidor comum. O preço pode subir ou cair.
    </p>

</div>

