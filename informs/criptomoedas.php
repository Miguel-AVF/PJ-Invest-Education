<div class="informa_intro">

    <h1>Crptomoedas</h1>

    <p>
        As criptomoedas são ativos digitais que utilizam tecnologias criptográficas e redes de computadores para registrar, validar e realizar transações. Muitas funcionam por meio de uma tecnologia chamada blockchain, que permite armazenar informações em um registro digital distribuído, sem depender necessariamente de uma instituição financeira central. <br>
        Diferentemente dos investimentos tradicionais, como CDBs e títulos do Tesouro Direto, as criptomoedas não representam, em geral, empréstimos a bancos ou ao governo. Seu valor depende de fatores como oferta e demanda, utilidade da rede, adoção pelo mercado, tecnologia e confiança dos participantes. <br>
        Cada criptomoeda possui características e finalidades próprias. Algumas são utilizadas como meio de transferência de valores, outras permitem executar contratos inteligentes e desenvolver aplicações digitais, enquanto algumas buscam manter seu preço estável em relação a moedas tradicionais, como o dólar.

    </p>

</div>

<div class="explica">

    <h2>BTC – Bitcoin</h2>

    <p>
        O Bitcoin é a primeira criptomoeda criada e foi desenvolvido para permitir transferências de valores pela internet sem depender diretamente de bancos ou outras instituições financeiras. Sua rede funciona de maneira descentralizada, utilizando a tecnologia blockchain para registrar e validar as transações. <br>
        Uma de suas principais características é a quantidade máxima de 21 milhões de unidades, estabelecida em seu protocolo. Por esse motivo, o Bitcoin é frequentemente associado à escassez digital e utilizado por investidores que buscam exposição a esse tipo de ativo. <br>
        Seu preço é determinado pela oferta e demanda do mercado, podendo apresentar grandes oscilações.
    </p>

</div>

<div class="explica">

    <h2>ETH – Ethereum</h2>

    <p>
        O Ethereum é uma plataforma baseada em blockchain que permite realizar transferências de valores e executar contratos inteligentes, conhecidos como smart contracts. Esses contratos são programas que executam determinadas ações automaticamente quando as condições estabelecidas são atendidas. <br>
        O ETH, também chamado de Ether, é a criptomoeda nativa da rede Ethereum. Ele é utilizado para pagar taxas de transação e processamento, além de participar do mecanismo de validação da rede por meio do sistema de prova de participação (Proof of Stake). <br>
        Diferentemente do Bitcoin, o Ethereum não foi desenvolvido apenas para funcionar como uma moeda digital, mas também como uma infraestrutura para aplicações descentralizadas, serviços financeiros digitais e outros projetos.
    </p>

</div>

<div class="explica">

    <h2>USDT – Tether</h2>

    <p>
        O USDT é uma stablecoin, ou seja, uma criptomoeda desenvolvida para manter seu valor próximo ao de uma moeda tradicional. Nesse caso, o Tether busca acompanhar o dólar americano, seguindo uma referência de 1 USDT para 1 dólar. <br>
        Sua principal finalidade é permitir movimentações e negociações dentro do mercado de criptomoedas com menor exposição às oscilações de preço comuns em ativos como Bitcoin e Ethereum. <br>
        O USDT é utilizado em corretoras, carteiras digitais e diferentes redes blockchain. Entretanto, sua estabilidade não é uma garantia absoluta, pois depende da manutenção da paridade, das reservas da empresa emissora e das condições de mercado.
    </p>

</div>

<div class="explica">

    <h2>BNB - (Build and Build/Binance Coin)</h2>

    <p>
        O BNB, anteriormente conhecido como Binance Coin, é o token nativo do ecossistema BNB Chain. Seu nome passou a representar a expressão Build and Build, que está relacionada ao desenvolvimento e à expansão desse ecossistema. <br>
        O BNB possui diversas utilidades, sendo utilizado principalmente para pagar taxas de transação na BNB Smart Chain, participar de mecanismos de staking e interagir com aplicações descentralizadas. <br>
        Outra característica é o mecanismo de queima de tokens (burn), que consiste na retirada permanente de determinadas unidades de circulação, com o objetivo de reduzir gradualmente a quantidade total de BNB. <br>
        Seu valor de mercado varia conforme a oferta e a demanda, além da utilização e do desenvolvimento do ecossistema BNB Chain.
    </p>

</div>

<div class="explica">
    
    <h2>SOL - Solana</h2>

    <p>
        A Solana é uma plataforma blockchain desenvolvida para permitir transações rápidas e processamento de aplicações descentralizadas. Sua infraestrutura busca oferecer alta capacidade de processamento e custos relativamente baixos para as operações realizadas na rede. <br>
        O SOL é a criptomoeda nativa da plataforma e possui diferentes funções, como pagar taxas de transação, participar do processo de validação da rede e realizar staking. <br>
        A rede Solana também permite o desenvolvimento de contratos inteligentes, aplicações financeiras descentralizadas, jogos e outros projetos digitais. <br>
        Assim como outras criptomoedas, o SOL está sujeito às oscilações do mercado. Sua valorização depende de fatores como adoção da rede, atividade dos usuários, desenvolvimento tecnológico e demanda pelo ativo.
    </p>

</div>

<div>

