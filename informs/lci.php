<div class="informa_intro">

    <h1>LCI – Letra de Crédito Imobiliário</h1>

    <p>
        A LCI significa Letra de Crédito Imobiliário. É um título de renda fixa emitido por instituições financeiras para captar recursos destinados ao financiamento do setor imobiliário. 
        Ao investir, a pessoa empresta recursos à instituição emissora e recebe remuneração conforme as condições contratadas. <br>
        Assim como acontece com CDBs, a análise não deve se limitar à taxa anunciada. É necessário observar o emissor, o prazo, a carência, a liquidez, o tipo de remuneração e as condições de vencimento. <br>
        A LCI pode apresentar remuneração pós-fixada, prefixada ou híbrida, dependendo da oferta da instituição financeira.
    </p>

</div>

<div class="explica">

    <h2>LCI 90% do CDI</h2>

    <p>
        Uma LCI que oferece 90% do CDI tem sua remuneração calculada com base em 90% da variação do CDI durante o período, conforme as regras do título. O percentual não significa lucro de 90% sobre o valor aplicado. <br>
        Os rendimentos de LCI para pessoa física são atualmente isentos de Imposto de Renda. Por isso, a comparação com outros investimentos deve considerar a rentabilidade líquida, o prazo e a liquidez.
    </p>

</div>

<div class="explica">

    <h2>LCI 95% do CDI</h2>

    <p>
        A LCI a 95% do CDI acompanha o indicador em uma proporção maior do que uma LCI a 90% do CDI, mantendo-se iguais as demais condições. <br>
        Mesmo assim, a taxa mais alta não garante que seja a melhor opção. O prazo de carência, o vencimento, o emissor e a necessidade de resgatar o dinheiro podem mudar a comparação.
    </p>

</div>

<div class="explica">

    <h2>LCI 100% do CDI</h2>

    <p>
        A LCI a 100% do CDI acompanha integralmente a variação do CDI, segundo a metodologia e as condições do título. <br>
        Para avaliar sua atratividade, compare-a com outras opções de renda fixa, considerando que a isenção de Imposto de Renda para pessoa física pode fazer diferença na rentabilidade líquida.
    </p>

</div>

<div class="explica">

    <h2>LCI prefixada</h2>

    <p>
        Na LCI prefixada, a taxa é definida no momento da aplicação. Isso permite conhecer a taxa contratada, desde que o investimento seja mantido conforme as condições previstas até o vencimento. <br>
        A taxa fixa não elimina o custo de oportunidade: se as taxas de mercado subirem depois da aplicação, novos títulos poderão oferecer remuneração maior.
    </p>

</div>

<div class="explica">

    <h2>LCI IPCA + taxa fixa</h2>

    <p>
        A LCI híbrida combina a variação do IPCA, índice oficial de inflação, com uma taxa adicional fixa. <br>
        Sua lógica é acompanhar a inflação e acrescentar a taxa contratada. É importante verificar o prazo e as condições do título, pois a proteção do poder de compra depende da remuneração efetiva e do período em que o dinheiro fica aplicado.
    </p>

</div>

