    <div class="informa_intro">

        <h1>CDB — Certificado de Depósito Bancário</h1>

        <p>
            CDB é um título emitido por instituições financeiras. Ao aplicar em um CDB, o investidor está, de 
            forma simplificada, emprestando dinheiro à instituição emissora, que remunera esse dinheiro 
            segundo as condições do título. <br>
            A comparação entre CDBs não deve olhar apenas para o percentual do CDI. Também é importante 
            observar liquidez, prazo, emissor, tributação, forma de remuneração e condições para resgate.
        </p>

    </div>
    
    <div class="explica">

        <h2>CDB 100% do CDI com liquidez diária</h2>

        <p>
            Esse tipo acompanha o CDI segundo as condições definidas pelo produto e permite resgate diário 
            quando a liquidez é realmente diária. Por isso, é um exemplo comum para estudar a relação entre 
            rendimento e disponibilidade do dinheiro.<br> 
            O ponto principal é entender que liquidez não significa necessariamente ausência de risco ou 
            rendimento garantido. O produto precisa ser analisado pelas regras do emissor e pelas proteções 
            aplicáveis. 
        </p>

    </div>

    <div class="explica">

        <h2>CDB 105% e 110% do CDI</h2>

        <p>
            Quando um CDB oferece 105% do CDI, o percentual indica uma remuneração equivalente a 105% da variação do CDI durante o período, conforme as regras do título. Isso não significa que o investidor receberá 105% de lucro sobre o dinheiro investido <br>
            A rentabilidade acompanha o indicador, sendo importante considerar o prazo, a liquidez e a tributação para avaliar o retorno líquido do investimento.
        </p>

    </div>

    <div class="explica">

        <h2>CDB 110% do CDI</h2>

        <p>
            Quando um CDB oferece 110% do CDI, sua remuneração corresponde a 110% da variação do CDI durante o período, conforme as condições contratadas. <br>
            Embora apresente uma taxa maior que um CDB de 105% do CDI, é importante verificar se essa rentabilidade está associada a um prazo maior ou a uma menor liquidez. Portanto, comparar apenas os percentuais pode levar a uma análise incompleta.
        </p>

    </div>

    <div class="explica">

        <h2>CDB prefixado</h2>

        <p>
            No prefixado, a taxa contratada é conhecida no momento da aplicação. Se o título for levado até 
            as condições previstas, a taxa contratada permite saber qual é a lógica de remuneração. Porém, 
            isso não elimina o risco de mercado caso o investidor queira vender ou resgatar antes do 
            vencimento.
        </p>

    </div>


    <div class="explica">

        <h2>CDB IPCA + taxa fixa</h2>
        
        <p>
            Nesse formato, a remuneração combina a variação do IPCA com uma taxa adicional definida no 
            título. A lógica é relacionar o investimento à inflação mais uma parcela adicional, o que pode ser 
            estudado para objetivos de prazo mais longo.
        </p>

    </div>

    <h3>Risco, liquidez e rentabilidade </h3>

    <p>
        Três palavras aparecem o tempo todo em educação financeira: risco, liquidez e rentabilidade. Risco 
        está relacionado à possibilidade de resultados diferentes do esperado ou de perdas; liquidez indica 
        a facilidade e as condições para transformar o investimento em dinheiro disponível; rentabilidade 
        mostra quanto o investimento pode render.<br> 
        Um produto com maior rentabilidade potencial não é automaticamente adequado para todos os 
        objetivos. O prazo e a necessidade de acesso ao dinheiro mudam a análise.
    </p>

    <h3>CDB — Tributação e exemplos </h3>

    <p>
        Em muitos CDBs para pessoa física, a tributação de renda segue a tabela regressiva do Imposto 
        de Renda para renda fixa, de acordo com o prazo. Também é necessário considerar o IOF em 
        situações de resgate muito curto, conforme as regras vigentes.<br> 
        Exemplo didático: suponha dois CDBs com a mesma quantia inicial. Um oferece liquidez diária e 
        outro paga uma taxa maior, mas exige permanência até uma data específica. O segundo não deve 
        ser comparado apenas pela taxa: se o dinheiro puder ser necessário antes, a liquidez passa a ser 
        parte importante da decisão.
    </p>

