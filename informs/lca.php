<div class="informa_intro">

    <h1>LCA – Letra de Crédito do Agronegócio</h1>

    <p>
        A LCA significa Letra de Crédito do Agronegócio. É um título de renda fixa emitido por instituições financeiras para captar recursos destinados ao financiamento do agronegócio. <br>
        Ao investir em uma LCA, a pessoa empresta recursos à instituição emissora e recebe remuneração conforme as condições estabelecidas no momento da aplicação. <br>
        Assim como acontece com outros investimentos de renda fixa, a análise não deve considerar apenas a taxa de rentabilidade. É necessário observar o emissor, o prazo, a carência, a liquidez e as condições de vencimento. <br>
        A LCA pode apresentar remuneração pós-fixada, prefixada ou híbrida, dependendo da oferta da instituição financeira.
    </p>

</div>

<div class="explica">

    <h2>LCA 90% do CDI</h2>

    <p>
        A LCA a 90% do CDI utiliza o CDI como referência de remuneração, pagando o percentual previsto no título.<br>
        Sua ligação econômica é com o financiamento do agronegócio. Para decidir se é adequada, compare o rendimento líquido, o prazo, a carência e a solidez da instituição emissora, sem presumir que toda LCA tenha liquidez diária.
    </p>

</div>

<div class="explica">

    <h2>LCA 95% do CDI</h2>

    <p>
        A LCA a 95% do CDI remunera conforme uma proporção de 95% do indicador.<br>
        A diferença em relação a uma LCA de 90% pode parecer pequena, mas o resultado depende também do prazo, do momento da aplicação e das condições contratuais. <br>
        Uma taxa maior pode vir acompanhada de um período de carência mais longo.
    </p>

</div>

<div class="explica">

    <h2>LCA 100% do CDI</h2>
    
    <p>
        A LCA a 100% do CDI acompanha integralmente o CDI, conforme as condições do contrato. <br>
        Os rendimentos de LCA para pessoa física são atualmente isentos de Imposto de Renda, mas o investidor deve conferir as regras tributárias vigentes e suas obrigações de declaração. <br>
        A isenção não elimina os riscos de crédito nem garante resgate imediato.
    </p>

</div>

<div class="explica">

    <h2>LCA prefixada</h2>

    <p>
        Na LCA prefixada, a taxa de remuneração é estabelecida no momento da contratação. <br>
        O investidor consegue conhecer a taxa prevista para o prazo contratado, mas deve avaliar o vencimento e a possibilidade de precisar do dinheiro antes. <br>
        A venda antecipada, quando permitida, pode depender das condições de mercado e não deve ser presumida como garantida.
    </p>

</div>

<div class="explica">

    <h2>LCA + taxa fixa</h2>

    <p>
        A LCA híbrida combina a inflação medida pelo IPCA com uma taxa adicional contratada. <br>
        Essa estrutura pode ser estudada para objetivos de médio ou longo prazo, mas sua adequação depende do vencimento, da carência e do objetivo financeiro. <br>
        O rendimento final também depende da inflação observada durante o período.
    </p>

</div>

